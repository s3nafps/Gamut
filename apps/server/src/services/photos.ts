import { randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { AppError, PHOTO_MAX_BYTES } from '@gamut/core';
import { and, eq } from 'drizzle-orm';
import type { Db } from '../db/client';
import * as s from '../db/schema';

const EXT: Record<string, string> = { 'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp' };

/** Photos are stored as files in the uploads folder; the database keeps who/when/what. */
export async function savePhoto(
  db: Db,
  uploadDir: string,
  unitId: number,
  input: { data: string; mime: string; caption: string; ticketId?: number | null; testId?: number | null },
  userId: number,
) {
  const [unit] = await db.select({ id: s.units.id }).from(s.units).where(eq(s.units.id, unitId));
  if (!unit) throw new AppError('not_found', 404);
  // The ticket / test must belong to this unit.
  if (input.ticketId) {
    const [t] = await db.select({ id: s.tickets.id }).from(s.tickets).where(and(eq(s.tickets.id, input.ticketId), eq(s.tickets.unitId, unitId)));
    if (!t) throw new AppError('invalid_input');
  }
  if (input.testId) {
    const [t] = await db.select({ id: s.tests.id }).from(s.tests).where(and(eq(s.tests.id, input.testId), eq(s.tests.unitId, unitId)));
    if (!t) throw new AppError('invalid_input');
  }
  const bytes = Buffer.from(input.data, 'base64');
  if (bytes.length === 0) throw new AppError('invalid_input');
  if (bytes.length > PHOTO_MAX_BYTES) throw new AppError('photo_too_large', 413);
  const key = `${unitId}-${Date.now()}-${randomBytes(6).toString('hex')}.${EXT[input.mime] ?? 'bin'}`;
  await mkdir(uploadDir, { recursive: true });
  await writeFile(join(uploadDir, key), bytes);
  const [row] = await db
    .insert(s.attachments)
    .values({
      unitId,
      ticketId: input.ticketId ?? null,
      testId: input.testId ?? null,
      storageKey: key,
      mime: input.mime,
      size: bytes.length,
      caption: input.caption,
      uploadedBy: userId,
    })
    .returning();
  await db.insert(s.events).values({ unitId, ticketId: input.ticketId ?? null, type: 'photo_added', userId, data: { attachmentId: row.id } });
  return row;
}

export async function readPhoto(db: Db, uploadDir: string, id: number) {
  const [row] = await db.select().from(s.attachments).where(eq(s.attachments.id, id));
  if (!row) throw new AppError('not_found', 404);
  // storageKey is generated by us (no user input), so it cannot point outside the folder.
  const data = await readFile(join(uploadDir, row.storageKey)).catch(() => null);
  if (!data) throw new AppError('not_found', 404);
  return { row, data };
}
